"""Generate a hashed CPython 3.12 / Windows x64 wheel lock from an input file."""

from __future__ import annotations

import argparse
import hashlib
import importlib.metadata
import re
import subprocess
import sys
import tempfile
import zipfile
from dataclasses import dataclass
from email.parser import BytesParser
from pathlib import Path

try:
    from scripts.dependency_lock_policy import LOCK_GENERATOR_PIP_VERSION
except ModuleNotFoundError:
    from dependency_lock_policy import LOCK_GENERATOR_PIP_VERSION


PROJECT_ROOT = Path(__file__).resolve().parents[1]
TARGET_PYTHON_VERSION = "3.12"
TARGET_PLATFORM = "win_amd64"
TARGET_ABI = "cp312"
NORMALIZED_NAME_PATTERN = re.compile(r"[-_.]+")


class LockGenerationError(RuntimeError):
    """Raised when wheel resolution cannot produce a deterministic lock."""


@dataclass(frozen=True)
class WheelRecord:
    name: str
    version: str
    sha256: str

    @property
    def normalized_name(self) -> str:
        return NORMALIZED_NAME_PATTERN.sub("-", self.name).lower()


def _wheel_metadata_path(wheel_path: Path) -> str:
    with zipfile.ZipFile(wheel_path) as wheel:
        metadata_paths = sorted(
            path
            for path in wheel.namelist()
            if "/" not in path.removesuffix(".dist-info/METADATA")
            and path.endswith(".dist-info/METADATA")
        )
    if len(metadata_paths) != 1:
        raise LockGenerationError(
            f"{wheel_path.name} must contain exactly one .dist-info/METADATA file."
        )
    return metadata_paths[0]


def wheel_record(wheel_path: Path) -> WheelRecord:
    """Read the package identity and SHA-256 from one wheel."""
    try:
        metadata_path = _wheel_metadata_path(wheel_path)
        with zipfile.ZipFile(wheel_path) as wheel:
            metadata = BytesParser().parsebytes(wheel.read(metadata_path))
    except (OSError, zipfile.BadZipFile) as exc:
        raise LockGenerationError(f"Unable to read wheel {wheel_path}: {exc}") from exc

    name = metadata.get("Name")
    version = metadata.get("Version")
    if not name or not version:
        raise LockGenerationError(f"{wheel_path.name} has incomplete package metadata.")

    return WheelRecord(
        name=name,
        version=version,
        sha256=hashlib.sha256(wheel_path.read_bytes()).hexdigest(),
    )


def records_from_wheel_directory(wheel_directory: Path) -> tuple[WheelRecord, ...]:
    """Return the unique resolved package set represented by downloaded wheels."""
    wheel_paths = sorted(wheel_directory.glob("*.whl"))
    if not wheel_paths:
        raise LockGenerationError(f"No wheels were downloaded to {wheel_directory}.")

    by_name: dict[str, WheelRecord] = {}
    for wheel_path in wheel_paths:
        record = wheel_record(wheel_path)
        existing = by_name.get(record.normalized_name)
        if existing is not None and existing != record:
            raise LockGenerationError(
                f"Conflicting wheels for {record.normalized_name}: "
                f"{existing.version} and {record.version}."
            )
        by_name[record.normalized_name] = record

    return tuple(sorted(by_name.values(), key=lambda record: record.normalized_name))


def render_lock(records: tuple[WheelRecord, ...], source_input: Path) -> str:
    """Render a deterministic pip --require-hashes compatible requirements file."""
    lines = [
        "# Generated by scripts/generate_windows_lock.py; do not edit manually.",
        f"# Source: {source_input.as_posix()}",
        "# Target: CPython 3.12 on Windows x64 (win_amd64).",
        f"# Resolver: pip=={LOCK_GENERATOR_PIP_VERSION}.",
        "",
    ]
    lines.extend(
        f"{record.normalized_name}=={record.version} --hash=sha256:{record.sha256}"
        for record in records
    )
    return "\n".join(lines) + "\n"


def _assert_generator_environment() -> None:
    if sys.version_info[:2] != (3, 12):
        raise LockGenerationError("Lock generation requires CPython 3.12.")
    pip_version = importlib.metadata.version("pip")
    if pip_version != LOCK_GENERATOR_PIP_VERSION:
        raise LockGenerationError(
            f"Lock generation requires pip=={LOCK_GENERATOR_PIP_VERSION}, got {pip_version}."
        )


def download_wheels(requirements_input: Path, wheel_directory: Path) -> None:
    """Resolve only Windows CPython 3.12 binary wheels for one input manifest."""
    command = [
        sys.executable,
        "-m",
        "pip",
        "download",
        "--disable-pip-version-check",
        "--dest",
        str(wheel_directory),
        "--only-binary=:all:",
        "--platform",
        TARGET_PLATFORM,
        "--python-version",
        TARGET_PYTHON_VERSION,
        "--implementation",
        "cp",
        "--abi",
        TARGET_ABI,
        "-r",
        str(requirements_input),
    ]
    result = subprocess.run(command, check=False)
    if result.returncode:
        raise LockGenerationError(f"pip download failed with exit code {result.returncode}.")


def generate_lock(
    requirements_input: Path,
    output_path: Path,
    *,
    wheel_directory: Path | None = None,
) -> tuple[WheelRecord, ...]:
    """Resolve wheels or use a supplied wheel directory, then atomically write a lock."""
    _assert_generator_environment()
    requirements_input = requirements_input.resolve()
    output_path = output_path.resolve()
    if not requirements_input.is_file():
        raise LockGenerationError(f"Input manifest does not exist: {requirements_input}")

    temporary_directory: tempfile.TemporaryDirectory[str] | None = None
    if wheel_directory is None:
        temporary_directory = tempfile.TemporaryDirectory(prefix="ytsd-lock-")
        wheel_directory = Path(temporary_directory.name)
        download_wheels(requirements_input, wheel_directory)
    else:
        wheel_directory = wheel_directory.resolve()

    try:
        records = records_from_wheel_directory(wheel_directory)
        try:
            source_input = requirements_input.relative_to(PROJECT_ROOT)
        except ValueError:
            source_input = requirements_input
        rendered = render_lock(records, source_input)
        output_path.parent.mkdir(parents=True, exist_ok=True)
        temporary_output = output_path.with_suffix(output_path.suffix + ".tmp")
        temporary_output.write_text(rendered, encoding="utf-8", newline="\n")
        temporary_output.replace(output_path)
        return records
    finally:
        if temporary_directory is not None:
            temporary_directory.cleanup()


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Generate a hash-locked Windows CPython 3.12 requirements file."
    )
    parser.add_argument("--input", required=True, type=Path, help="Human-maintained .in file.")
    parser.add_argument("--output", required=True, type=Path, help="Generated .lock file.")
    parser.add_argument(
        "--wheel-dir",
        type=Path,
        help="Use pre-downloaded wheels instead of running pip download.",
    )
    args = parser.parse_args()

    try:
        records = generate_lock(args.input, args.output, wheel_directory=args.wheel_dir)
    except LockGenerationError as exc:
        parser.error(str(exc))

    print(f"Wrote {args.output} with {len(records)} hash-locked packages.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
